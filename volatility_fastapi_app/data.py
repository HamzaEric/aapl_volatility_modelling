"""Data access layer for the Volatility Forecasting Pipeline.

This module provides the data pipeline for fetching real-world 
market data using Yahoo Finance (via yf_loader), caching it 
in a local SQLite database, and wrangling it for GARCH volatility modeling.

Classes
-------
SQLRepository
    Reads from and writes to a SQLite database using pandas and sqlite3.

Functions
---------
wrangle_data(repo, ticker, n_observations)
    Fetch daily prices from the local SQLite database and 
    return daily percentage returns as a pd.Series.
"""

from __future__ import annotations

import sqlite3
import pandas as pd

# Import your real-world data loader
from yf_loader import get_daily_data


class SQLRepository:
    """Read from and write to a SQLite database.

    Parameters
    ----------
    connection : sqlite3.Connection
        An open database connection.
    """

    def __init__(self, connection: sqlite3.Connection) -> None:
        self.connection = connection

    def insert_table(
        self,
        table_name: str,
        records: pd.DataFrame,
        if_exists: str = "fail",
    ) -> dict:
        """Write *records* into the database.

        Parameters
        ----------
        table_name : str
            Target table name.
        records : pd.DataFrame
            Data to insert.
        if_exists : str, optional
            ``"fail"``, ``"replace"``, or ``"append"``. Default is ``"fail"``.

        Returns
        -------
        dict
            ``{"transaction_successful": bool, "records_inserted": int}``
        """
        # Pandas to_sql handles the database insertion directly
        n_inserted = records.to_sql(
            name=table_name,
            con=self.connection,
            if_exists=if_exists,
        )
        
        return {
            "transaction_successful": True,
            "records_inserted": n_inserted if n_inserted is not None else len(records)
        }

    def read_table(self, table_name: str, limit: int | None = None) -> pd.DataFrame:
        # Sort descending to get the newest data first
        query = f'SELECT * FROM "{table_name}" ORDER BY date DESC'
        if limit is not None:
            query += f" LIMIT {limit}"

        df = pd.read_sql(sql=query, con=self.connection, index_col="date")
        df.index = pd.to_datetime(df.index)
        df = df.astype(float)
        return df


def wrangle_data(repo: SQLRepository, ticker: str, n_observations: int = None) -> pd.Series:
    """Fetch daily prices and return percentage returns.

    Parameters
    ----------
    repo : SQLRepository
        The database repository containing the cached data.
    ticker : str
        Stock ticker symbol.
    n_observations : int, optional
        Number of return observations to keep. If None, returns all history.

    Returns
    -------
    pd.Series
        Named ``"return"``, ``DatetimeIndex``, no NaN.
    """
    # 1. Fetch data from the database. 
    # If n_observations is passed, pull n + 1 to account for the NaN drop during pct_change()
    limit = n_observations + 1 if n_observations else None
    df = repo.read_table(table_name=ticker, limit=limit)
    
    # 2. Sort dates in ascending order (oldest to newest) 
    df.sort_index(ascending=True, inplace=True)
    
    # 3. Calculate daily percentage returns
    returns = df["close"].pct_change() * 100
    
    # 4. Name the Series
    returns.name = "return"
    
    # 5. Drop the NaN value generated by pct_change()
    returns.dropna(inplace=True)
    
    return returns