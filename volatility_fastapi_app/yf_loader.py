"""Yahoo Finance data loader for US equities.

This module fetches real market data directly into a pandas DataFrame
using native yfinance parameters (period, start, end).
"""

import warnings
import yfinance as yf
import pandas as pd

def get_daily_data(
    symbol: str,
    period: str = "max",
    start: str = None,
    end: str = None
) -> pd.DataFrame:
    """Fetch daily time series data using Yahoo Finance natively.

    Parameters
    ----------
    symbol : str
        The ticker symbol (e.g., "AAPL" or "NVDA").
    period : str, default "max"
        Valid periods: 1d, 5d, 1mo, 3mo, 6mo, 1y, 2y, 5y, 10y, ytd, max.
        Ignored if start/end are provided.
    start : str, optional
        Download start date string (YYYY-MM-DD).
    end : str, optional
        Download end date string (YYYY-MM-DD).

    Returns
    -------
    pd.DataFrame
        A DataFrame indexed by Date (DatetimeIndex) with lowercase
        column names (open, high, low, close, volume).
    """
    # Ensure the ticker symbol is uppercase
    yf_symbol = symbol.upper()

    try:
        ticker = yf.Ticker(yf_symbol)

        # Fetch using native yfinance arguments
        if start or end:
            df = ticker.history(start=start, end=end)
        else:
            df = ticker.history(period=period)

        if df.empty:
            warnings.warn(f"No data found for symbol '{yf_symbol}'.")
            return pd.DataFrame()

        # Clean up columns to match your previous task requirements
        columns_to_keep = ["Open", "High", "Low", "Close", "Volume"]
        df = df[[col for col in columns_to_keep if col in df.columns]]

        # Lowercase column names so 'Close' becomes 'close'
        df.columns = [col.lower() for col in df.columns]

        # Standardize index
        df.index.name = "date"
        if df.index.tz is not None:
            df.index = df.index.tz_localize(None)

        return df

    except Exception as e:
        warnings.warn(f"Failed to fetch data for {yf_symbol}. Error: {e}")
        return pd.DataFrame()